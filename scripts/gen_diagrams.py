def degradation() -> None:
    causes = {
        DegradationReason.NO_CONSENT: "caller declined recording",
        DegradationReason.INTAKE_DECLINED: "caller pressed 2",
        DegradationReason.STT_UNAVAILABLE: "speech worker down",
        DegradationReason.LLM_UNAVAILABLE: "model down or too slow",
        DegradationReason.CORE_DATA_UNAVAILABLE: "bank core unreachable",
        DegradationReason.CORE_DATA_STALE: "served from cache",
        DegradationReason.LOW_ASSURANCE: "identity not strong enough",
        DegradationReason.MEDIA_FORK_FAILED: "no audio to transcribe",
        DegradationReason.TIMED_OUT: "stage exceeded its budget",
    }
    lines = [
        "flowchart LR",
        f"    FULL[{lbl('FULL BRIEF', 'context + speech + AI')}]:::ok",
    ]
    ctx = lbl("CONTEXT-ONLY BRIEF", "data + keypad menu", "BUILT AT P1 - never fails")
    lines.append(f"    CTX[{ctx}]:::warn")
    lines.append(f"    MIN[{lbl('MINIMAL', 'queue + what they pressed')}]:::bad")
    lines.append(f"    CALL[{lbl('THE CALL CONNECTS ANYWAY', '(D12)')}]:::always")
    for reason, why in causes.items():
        node = "R_" + reason.name
        lines.append(f"    FULL -- {lbl(str(reason), why)} --> {node}[ ]:::dot")
        target = "MIN" if reason in {DegradationReason.CORE_DATA_UNAVAILABLE} else "CTX"
        lines.append(f"    {node} --> {target}")
    lines.append("    CTX --> CALL")
    lines.append("    MIN --> CALL")
    lines.append("    classDef ok fill:#e9f7ef,stroke:#2f9e5f,color:#08361d")
    lines.append("    classDef warn fill:#fff4e6,stroke:#e8a33d,color:#4a2f00")
    lines.append("    classDef bad fill:#fdecea,stroke:#d93025,color:#5c1a13")
    lines.append("    classDef always fill:#1f6feb,stroke:#0b3d91,color:#fff")
    lines.append("    classDef dot fill:#fff,stroke:#ccc,color:#666")
    write("degradation_ladder", "\n".join(lines), src="readycall.domain.enums.DegradationReason")


