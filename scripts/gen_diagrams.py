def product_lines(pack: DomainPack) -> None:
    lines = ["flowchart TB", f"    ROOT[{q('ProductLine')}]:::root"]
    for line in ProductLine:
        intents = [c for c, s in pack.intents.items() if s.line is line]
        label = f"{line}\n{len(intents)} intents"
        lines.append(f"    ROOT --> L_{line.name}[{q(label)}]:::line")
        for code in sorted(intents):
            spec = pack.intents[code]
            mark = " *catch-all*" if spec.is_catch_all else ""
            lines.append(f"    L_{line.name} --> i_{code.replace('.', '_')}[{q(code + mark)}]")
    lines.append("    classDef root fill:#1f6feb,stroke:#0b3d91,color:#fff")
    lines.append("    classDef line fill:#eef4ff,stroke:#5b8def,color:#0b2545")
    write("product_lines", "\n".join(lines), src="ProductLine enum + config/intents.yaml")


