"""Generate the diagrams that can be derived from source, so they cannot drift.

    uv run python scripts/gen_diagrams.py

Every diagram this script emits is built by *reading the running system* — the transition
table, the loaded domain pack, the pydantic models, the event registry, the adapter
packages on disk. None of it is transcribed by hand, which is the point: a diagram that is
retyped from memory is a comment, and comments rot. These are closer to tests.

Hand-drawn diagrams (architecture, sequence flows, roadmaps) live beside the generated ones
in `docs/diagrams/src/` and are marked `handwritten` in the header of each file.

After running this, render to SVG with `scripts/render_diagrams.mjs`.
"""

