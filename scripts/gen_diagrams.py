def domain_models() -> None:
    import readycall.domain.models as m

    lines = ["classDiagram", "    direction TB"]
    for group, names in _MODEL_GROUPS.items():
        lines.append(f"    namespace {group} {{")
        for name in names:
            model = getattr(m, name, None)
            if model is None:
                raise SystemExit(f"model {name} named in _MODEL_GROUPS does not exist")
            lines.append(f"        class {name}")
        lines.append("    }")
    for name in (n for names in _MODEL_GROUPS.values() for n in names):
        model = getattr(m, name)
        fields = list(getattr(model, "model_fields", {}))
        shown = fields[:6]
        for f in shown:
            lines.append(f"    {name} : {f}")
        if len(fields) > len(shown):
            lines.append(f"    {name} : ...{len(fields) - len(shown)} more")
    for left, right, label in _RELATIONS:
        lines.append(f"    {left} --> {right} : {label}")
    write("domain_models", "\n".join(lines), src="readycall.domain.models (pydantic fields)")


# --------------------------------------------------------------------------------------
# 11. Product lines, so the "insurance is not just health" point is visible.
# --------------------------------------------------------------------------------------


def product_lines(pack: DomainPack) -> None:
    lines = ["flowchart TB", f"    ROOT[{q('ProductLine')}]:::root"]
    for line in ProductLine:
        intents = [c for c, s in pack.intents.items() if s.line is line]
        label = f"{line}\n{len(intents)} intents"
        lines.append(f"    ROOT --> L_{line.name}[{q(label)}]:::line")
        for code in sorted(intents):
            spec = pack.intents[code]
            mark = " *catch-all*" if spec.is_catch_all else ""
            lines.append(f"    L_{line.name} --> i_{code.replace('.', '_')}[{q(code + mark)}]")
    lines.append("    classDef root fill:#1f6feb,stroke:#0b3d91,color:#fff")
    lines.append("    classDef line fill:#eef4ff,stroke:#5b8def,color:#0b2545")
    write("product_lines", "\n".join(lines), src="ProductLine enum + config/intents.yaml")


def main() -> int:
    enable_utf8()
    pack = DomainPack.load(ROOT / "config")
    print("generating derived diagrams:")
    state_machine()
    state_machine_readable()
    menu_tree(pack)
    routing_chain(pack)
    dids(pack)
    event_catalogue()
    ports_adapters()
    assurance_ladder()
    agent_state()
    degradation()
    domain_models()
    product_lines(pack)
    where = OUT.relative_to(ROOT) if OUT.is_relative_to(ROOT) else OUT
    print()
    print(f"{len(list(OUT.glob('*.mmd')))} .mmd files in {where}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
