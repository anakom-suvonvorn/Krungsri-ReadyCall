BANNER = (
    "%% GENERATED by scripts/gen_diagrams.py - do not edit by hand.\n%% Source of truth: {src}\n"
)


def write(name: str, body: str, *, src: str) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / f"{name}.mmd").write_text(BANNER.format(src=src) + body.strip() + "\n", encoding="utf-8")
    print(f"  wrote {name}.mmd")


def q(text: str) -> str:
    """Quote a mermaid label so punctuation and Thai text survive."""
    return '"' + text.replace('"', "'") + '"'


def lbl(*parts: str) -> str:
    """Quote a multi-LINE mermaid label. Mermaid takes a literal newline in a label."""
    return q("\n".join(parts))


