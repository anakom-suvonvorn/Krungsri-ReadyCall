def db_schema() -> None:
    """Every table we write, read straight off the SQLAlchemy metadata.

    Generated rather than drawn because the whole claim of `D78` is *this* set and no more:
    a table that appears here without a reason, or a derived thing that quietly becomes a
    table, is exactly the drift the picture exists to prevent.
    """
    import readycall.db.models  # noqa: F401  (registers every table on the metadata)
    from readycall.db.base import Base

    tables = {name.split(".")[-1]: table for name, table in Base.metadata.tables.items()}
    grouped = {t for names in _TABLE_GROUPS.values() for t in names}
    ungrouped = tuple(sorted(set(tables) - grouped))
    groups = dict(_TABLE_GROUPS)
    if ungrouped:
        groups["other"] = ungrouped

    lines = ["flowchart TB"]
    # Enumerated, not hashed: `hash()` on a string is randomised per process, so a hashed
    # id would make this file differ between runs and `test_diagrams.py` would fail at
    # random. A generated diagram has to be byte-stable or the freshness check is noise.
    for n, (group, names) in enumerate(groups.items()):
        lines.append(f"    subgraph g_{n}[{q(group)}]")
        lines.append("        direction TB")
        for name in names:
            table = tables.get(name)
            if table is None:
                continue
            keys = [c.name for c in table.columns if c.primary_key]
            indexed = sorted({c.name for ix in table.indexes for c in ix.columns})
            jsonish = [
                c.name for c in table.columns if type(c.type).__name__ in {"Json", "JSON", "JSONB"}
            ]
            body = [f"<b>{name}</b>", "pk: " + ", ".join(keys)]
            if indexed:
                body.append("indexed: " + ", ".join(indexed))
            if jsonish:
                body.append("json: " + ", ".join(jsonish))
            body.append(f"{len(table.columns)} columns")
            lines.append(f"        t_{name}[{lbl(*body)}]:::tbl")
        lines.append("    end")

    for name, table in sorted(tables.items()):
        for fk in table.foreign_keys:
            target = fk.column.table.name
            if target != name:
                lines.append(f"    t_{name} -. {q('FK')} .-> t_{target}")

    lines.append(f"    D[{lbl('NOT tables, on purpose (D78)', '')}]:::hdr")
    for label, source, how in _DERIVED:
        assert source in tables, f"{source} is not a real table; _DERIVED is stale"
        node = "d_" + label.replace(" ", "_")
        lines.append(f"    D --- {node}[{lbl(label, how)}]:::derived")
        lines.append(f"    t_{source} == {q('derived from')} ==> {node}")

    lines.append("    classDef tbl fill:#e9f7ef,stroke:#2f9e5f,color:#08361d")
    lines.append("    classDef derived fill:#fffbe6,stroke:#d4a72c,color:#4a3800")
    lines.append("    classDef hdr fill:#fff,stroke:#d4a72c,color:#4a3800,stroke-dasharray:4 3")
    write("db_schema", chr(10).join(lines), src="readycall.db.models via Base.metadata")


def voice_prompts(pack: DomainPack, prompts: PromptPack) -> None:
    """Who asks for which line — read off the pack and the flow table.

    The point of drawing this is the arrows, not the boxes: a prompt id is a string in
    one file and a definition in another, and this is the only place the join is visible.
    An orphan shows up as a box nothing points at.
    """
    lines = ["flowchart LR"]
    referenced = prompts.referenced_ids(pack)

    lines.append('    subgraph flow["services/ivr asks by ROLE"]')
    for role in PromptRole:
        lines.append(f"        role_{role.value}[{q(role.value)}]:::role")
    lines.append("    end")

    lines.append('    subgraph cfg["menus.yaml + dids.yaml name an ID"]')
    for menu_id in sorted(pack.menus):
        lines.append(f"        menu_{menu_id}[{q(menu_id)}]:::cfg")
    for number in sorted(pack.dids):
        lines.append(f"        did_{number.replace('+', 'p')}[{q(number)}]:::cfg")
    lines.append("    end")

    def node(prompt_id: str) -> str:
        return "p_" + prompt_id.replace(".", "_")

    for prompt_id in sorted(prompts.prompts):
        spec = prompts.prompts[prompt_id]
        style = "dyn" if spec.is_dynamic else "static"
        suffix = f"{chr(10)}{{{', '.join(spec.slots)}}}" if spec.slots else ""
        lines.append(f"    {node(prompt_id)}[{q(prompt_id + suffix)}]:::{style}")

    for role, prompt_id in sorted(prompts.flow.items()):
        lines.append(f"    role_{role.value} --> {node(prompt_id)}")
    for menu_id, menu in sorted(pack.menus.items()):
        lines.append(f"    menu_{menu_id} --> {node(menu.prompt)}")
    for number, did in sorted(pack.dids.items()):
        lines.append(f"    did_{number.replace('+', 'p')} --> {node(did.greeting_prompt)}")

    orphans = sorted(set(prompts.prompts) - referenced)
    for prompt_id in orphans:
        lines.append(f"    class {node(prompt_id)} orphan")

    lines.append("    classDef role fill:#eef4ff,stroke:#5b8def,color:#0b2545")
    lines.append("    classDef cfg fill:#fff4e6,stroke:#e8a33d,color:#4a2f00")
    lines.append("    classDef static fill:#e9f7ef,stroke:#2f9e5f,color:#08361d")
    lines.append("    classDef dyn fill:#f3e8ff,stroke:#8b5cf6,color:#2e1065")
    lines.append("    classDef orphan fill:#ffe4e6,stroke:#e11d48,color:#4c0519")
    write(
        "voice_prompts",
        "\n".join(lines),
        src="config/voice_prompts.yaml + config/menus.yaml + config/dids.yaml",
    )


